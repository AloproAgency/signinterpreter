ALPHABET = set("abcdefghijklmnopqrstuvwxyz")


def download_dataset():
    """Download WLASL dataset from Kaggle."""
    try:
        import kagglehub
        print("Downloading WLASL dataset from Kaggle...")
        path = kagglehub.dataset_download("waseemnagahhenes/sign-language-dataset-wlasl-videos")
        print(f"Downloaded to: {path}")
        return path
    except Exception as e:
        print(f"Error downloading: {e}")
        print("Make sure kagglehub is installed and you're authenticated.")
        print("Run: pip install kagglehub && kagglehub login")
        sys.exit(1)


def find_video_dirs(download_path):
    """Find the directory containing video folders."""
    # The dataset structure may vary, look for directories with mp4 files
    for root, dirs, files in os.walk(download_path):
        mp4_files = [f for f in files if f.endswith('.mp4')]
        if mp4_files and dirs:
            return root
        if mp4_files and not dirs:
            return os.path.dirname(root)
    # Try common structures
    for candidate in [
        os.path.join(download_path, 'videos'),
        os.path.join(download_path, 'WLASL'),
        download_path,
    ]:
        if os.path.isdir(candidate):
            subdirs = [d for d in os.listdir(candidate) if os.path.isdir(os.path.join(candidate, d))]
            if subdirs:
                return candidate
    return download_path


def translate_and_copy(source_dir, target_dir):
    """Translate English folder names to French and copy videos."""
    os.makedirs(target_dir, exist_ok=True)

    folders = sorted([d for d in os.listdir(source_dir)
                      if os.path.isdir(os.path.join(source_dir, d))])

    print(f"Found {len(folders)} folders to translate")
    translated = 0
    skipped = 0
    kept_as_is = 0

    for folder in folders:
        src = os.path.join(source_dir, folder)
        folder_lower = folder.lower()

        # Skip single-letter alphabet folders (keep as-is)
        if folder_lower in ALPHABET:
            dst = os.path.join(target_dir, folder_lower)
            if not os.path.exists(dst):
                shutil.copytree(src, dst)
            kept_as_is += 1
            continue

        # Translate
        fr_name = TRANSLATIONS.get(folder_lower)
        if fr_name is None:
            print(f"  [NO TRANSLATION] {folder}")
            # Keep original name
            dst = os.path.join(target_dir, folder_lower)
            if not os.path.exists(dst):
                shutil.copytree(src, dst)
            skipped += 1
            continue

        dst = os.path.join(target_dir, fr_name)

        if os.path.exists(dst):
            # Merge: copy videos into existing folder
            for f in os.listdir(src):
                src_file = os.path.join(src, f)
                dst_file = os.path.join(dst, f)
                if os.path.isfile(src_file) and not os.path.exists(dst_file):
                    shutil.copy2(src_file, dst_file)
        else:
            shutil.copytree(src, dst)

        translated += 1

    print(f"\nDone! Translated: {translated}, Kept as-is: {kept_as_is}, No translation: {skipped}")
    print(f"Total folders in {target_dir}: {len(os.listdir(target_dir))}")


def main():
    parser = argparse.ArgumentParser(description='Download and translate WLASL dataset')
    parser.add_argument('--target', required=True, help='Target directory for translated dataset (e.g. /path/to/SL)')
    parser.add_argument('--source', help='Source directory (skip download if provided)')
    args = parser.parse_args()

    if args.source:
        source_dir = args.source
    else:
        download_path = download_dataset()
        source_dir = find_video_dirs(download_path)

    print(f"Source: {source_dir}")
    print(f"Target: {args.target}")
    print()

    # Verify source has video folders
    folders = [d for d in os.listdir(source_dir) if os.path.isdir(os.path.join(source_dir, d))]
    if not folders:
        print(f"ERROR: No folders found in {source_dir}")
        sys.exit(1)
    print(f"Found {len(folders)} source folders")

    # Check for duplicate translations
    fr_values = list(TRANSLATIONS.values())
    seen = {}
    for k, v in TRANSLATIONS.items():
        if v in seen:
            seen[v].append(k)
        else:
            seen[v] = [k]
    dupes = {k: v for k, v in seen.items() if len(v) > 1}
    if dupes:
        print(f"\nNote: {len(dupes)} French translations map from multiple English words (will be merged)")

    print()
    translate_and_copy(source_dir, args.target)


if __name__ == "__main__":
    main()
